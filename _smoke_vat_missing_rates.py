# -*- coding: utf-8 -*-
"""
Смоук-тест: защитный механизм «пропущенная ставка НДС» в шаге 14.

Проверяет Step14AccountsMixin._restore_missing_vat_rates()
(pipeline/steps/_step14_accounts.py) и встраивание в _process_revenue_9001:

1. Нет пропусков — строки и суммы не меняются, аудит пустой.
2. Пропуск + уникальный аналог по «ном_группа» -> восстановление ставки.
3. Пропуск + аналоги с несколькими ставками -> мода; равенство частот -> дефолт.
4. Пропуск без аналогов -> дефолт из параметров (nds_missing_values).
5. Текстовый маркер «Без НДС» -> ставка 0 (НЕ дефолт).
6. WARNING в логе и Excel-аудит в warnings/ появились.
7. Сквозной синтетический прогон _process_revenue_9001: 2 строки без ставки
   восстанавливаются до 22% по аналогам, выручка считается верно, сверка с ОСВ
   проходит, Excel-аудит пишется под именем компании. Тест не зависит от
   содержимого _INPUT_DATA (раньше здесь был «реальный кейс ГулБор» с зашитой
   цифрой и падал на любых других выгрузках).

Запуск: conda run -n fl_acc_card python -u _smoke_vat_missing_rates.py
"""
import shutil
import sys
from types import SimpleNamespace

import pandas as pd
from loguru import logger

from io_module.output_manager import configure_run, get_output_dir, get_run_dir
from pipeline.base import ProcessingContext
from pipeline.steps.step_14_build_opu_foundation import Step14BuildOpuFoundationStep

# --- Подготовка лога для проверок WARNING ---------------------------------
log_messages: list = []
_sink_id = logger.add(log_messages.append, level="WARNING")

# Инициализация папки вывода (нужна для warnings/)
configure_run()
run_dir = get_run_dir()

failures: list = []


def check(condition: bool, message: str) -> None:
    """Мини-ассерт с накоплением результата."""
    if condition:
        print(f"[OK] {message}")
    else:
        failures.append(message)
        print(f"[FAIL] {message}")


def warnings_text() -> str:
    return "\n".join(str(m) for m in log_messages)


# Константы для синтетических тестов
_CONTEXT = SimpleNamespace(company="smoke", period="test", run_id=None)
_STEP = Step14BuildOpuFoundationStep()


def make_df9001(rows):
    """Собирает df9001 (до groupby) для вызова _restore_missing_vat_rates.

    rows: список dict с ключами ном_группа/Сумма/ндс_ставка_исх/ндс_ставка.
    """
    df = pd.DataFrame([
        {
            "Имя_файла": "smoke_отчпровод_90.01_test.txt",
            "Документ": f"Документ {i + 1}",
            "контрагент": "Контрагент",
            "ном_группа": r["ном_группа"],
            "Сумма": r["Сумма"],
            "Сумма_руб": r["Сумма"],
            "ндс_ставка_исх": r.get("ндс_ставка_исх", "не_указано"),
            "ндс_ставка": r["ндс_ставка"],
        }
        for i, r in enumerate(rows)
    ])
    return df


# ==========================================================================
# Тест 1: нет пропусков
# ==========================================================================
print("\n--- Тест 1: нет пропусков -> ничего не меняется ---")
df1 = make_df9001([
    {"ном_группа": "Яйцо", "Сумма": 1100.0, "ндс_ставка": 0.10},
    {"ном_группа": "Яйцо", "Сумма": 2200.0, "ндс_ставка": 0.10},
    {"ном_группа": "Помет", "Сумма": 1220.0, "ндс_ставка": 0.22},
])
df1_out, audit1 = _STEP._restore_missing_vat_rates(df1, 0.22, _CONTEXT)
check(
    df1_out["ндс_ставка"].isna().sum() == 0
    and list(df1_out["ндс_ставка"]) == [0.10, 0.10, 0.22],
    "ставки не изменились",
)
check(audit1.empty, "аудит пуст (нет затронутых строк)")

# ==========================================================================
# Тест 2: пропуск + уникальный аналог
# ==========================================================================
print("\n--- Тест 2: пропуск + уникальный аналог по ном_группа ---")
df2 = make_df9001([
    {"ном_группа": "Помет", "Сумма": 1220.0, "ндс_ставка": 0.22},
    {"ном_группа": "Помет", "Сумма": 5000.0, "ндс_ставка": None},
    {"ном_группа": "Яйцо", "Сумма": 1100.0, "ндс_ставка": 0.10},
])
df2_out, audit2 = _STEP._restore_missing_vat_rates(df2, 0.22, _CONTEXT)
pomet_rates2 = df2_out.loc[df2_out["ном_группа"] == "Помет", "ндс_ставка"]
check(
    (pomet_rates2 - 0.22).abs().max() < 1e-9,
    "пропущенная ставка восстановлена по аналогам (0.22)",
)
check(
    len(audit2) == 1 and audit2.iloc[0]["источник"] == "аналоги",
    "аудит: 1 строка, источник «аналоги»",
)

# ==========================================================================
# Тест 3: несколько ставок у аналогов -> мода / tie -> дефолт
# ==========================================================================
print("\n--- Тест 3: разные ставки у аналогов -> мода; tie -> дефолт ---")
df3 = make_df9001([
    {"ном_группа": "ГруппаА", "Сумма": 1100.0, "ндс_ставка": 0.10},
    {"ном_группа": "ГруппаА", "Сумма": 1100.0, "ндс_ставка": 0.10},
    {"ном_группа": "ГруппаА", "Сумма": 1220.0, "ндс_ставка": 0.22},
    {"ном_группа": "ГруппаА", "Сумма": 1000.0, "ндс_ставка": None},
    {"ном_группа": "ГруппаБ", "Сумма": 1100.0, "ндс_ставка": 0.10},
    {"ном_группа": "ГруппаБ", "Сумма": 1220.0, "ндс_ставка": 0.22},
    {"ном_группа": "ГруппаБ", "Сумма": 1000.0, "ндс_ставка": None},
])
df3_out, audit3 = _STEP._restore_missing_vat_rates(df3, 0.22, _CONTEXT)
# Проверяем ТОЛЬКО восстановленные строки (в исходном df ставка была NaN)
was_missing3 = df3["ндс_ставка"].isna()
restored3 = df3_out.loc[was_missing3]
r3a = float(restored3.loc[restored3["ном_группа"] == "ГруппаА", "ндс_ставка"].iloc[0])
r3b = float(restored3.loc[restored3["ном_группа"] == "ГруппаБ", "ндс_ставка"].iloc[0])
check(abs(r3a - 0.10) < 1e-9, "мода аналогов: 0.10 (две из трёх)")
check(abs(r3b - 0.22) < 1e-9, "равенство частот -> дефолт 0.22")

# ==========================================================================
# Тест 4: пропуск без аналогов -> дефолт
# ==========================================================================
print("\n--- Тест 4: пропуск без аналогов -> дефолт из параметров ---")
df4 = make_df9001([
    {"ном_группа": "НовыйПродукт", "Сумма": 1000.0, "ндс_ставка": None},
])
df4_out, audit4 = _STEP._restore_missing_vat_rates(df4, 0.22, _CONTEXT)
check(abs(float(df4_out.iloc[0]["ндс_ставка"]) - 0.22) < 1e-9, "дефолтная ставка 0.22")
check(audit4.iloc[0]["источник"] == "дефолт", "аудит: источник «дефолт»")

# ==========================================================================
# Тест 5: явный маркер «Без НДС» -> 0, а НЕ дефолт
# ==========================================================================
print("\n--- Тест 5: текстовый маркер «Без НДС» -> ставка 0 ---")
df5 = make_df9001([
    {"ном_группа": "Экспорт", "Сумма": 1000.0,
     "ндс_ставка": None, "ндс_ставка_исх": "Без НДС"},
])
df5_out, audit5 = _STEP._restore_missing_vat_rates(df5, 0.22, _CONTEXT)
check(abs(float(df5_out.iloc[0]["ндс_ставка"])) < 1e-9, "явная нулевая ставка (0%), дефолт не применён")
check(audit5.iloc[0]["источник"] == "явная_0%", "аудит: источник «явная_0%»")

# ==========================================================================
# Тест 6: WARNING и Excel-аудит появились
# ==========================================================================
print("\n--- Тест 6: WARNING в логе и Excel-аудит в warnings/ ---")
check("НДС 90.01" in warnings_text(), "WARNING о восстановлении/дефолте записан в лог")
warn_files = list(get_output_dir("warnings").glob("nds_missing_rows_*.xlsx"))
check(len(warn_files) >= 1, f"Excel-аудит сохранён в warnings/ ({len(warn_files)} файл(ов))")

# ==========================================================================
# Тест 7: сквозной синтетический прогон _process_revenue_9001
# ==========================================================================
# Раньше здесь был «реальный кейс ГулБор»: загрузка настоящих выгрузок из
# _INPUT_DATA и сверка с зашитой цифрой 276 782,22 тыс.ед. Такой тест падал
# на любых других данных (у другого набора выгрузок нет ни этой компании, ни
# этой суммы) — то есть зависел от того, что сейчас лежит в папке.
# Теперь проводки и ОСВ синтетические, а проверяется то же самое по сути:
# сквозной путь шага 14 + восстановление ставок + сверка с ОСВ + Excel-аудит.
print("\n--- Тест 7: сквозной синтетический прогон 90.01 (2 строки без ставки) ---")
try:
    context = ProcessingContext(
        company="smoke_90_01",
        period="test",
        currency="RUB",
        tolerance_params={
            "tolerance_reconciliation": 200.0,
            "nds_missing_values": 0.22,
        },
    )

    # Три проводки по одной номенклатурной группе: одна со ставкой 22% (она же
    # аналог) и две без ставки — те самые «корректировки/возвраты». Сумма
    # 122 000 руб. = 100 000 + НДС 22 000, поэтому выручка без НДС = 100 тыс.ед.
    _SUM = 122_000.0
    transactions_all_df = pd.DataFrame([
        {
            "Имя_файла": "smoke_отчпровод_90.01_test.txt",
            "Документ": "Продажа 1",
            "Дт": "62.01",
            "Кт": "90.01",
            "Субконто Дт_1": "Покупатель 1",
            "Субконто Кт_1": "Группа",
            "Субконто Кт_2": "22%",
            "Сумма": _SUM,
            "Сумма_руб": _SUM,
        },
        {
            "Имя_файла": "smoke_отчпровод_90.01_test.txt",
            "Документ": "Корректировка 1",
            "Дт": "62.01",
            "Кт": "90.01",
            "Субконто Дт_1": "Покупатель 1",
            "Субконто Кт_1": "Группа",
            "Субконто Кт_2": "",
            "Сумма": _SUM,
            "Сумма_руб": _SUM,
        },
        {
            "Имя_файла": "smoke_отчпровод_90.01_test.txt",
            "Документ": "Корректировка 2",
            "Дт": "62.01",
            "Кт": "90.01",
            "Субконто Дт_1": "Покупатель 1",
            "Субконто Кт_1": "Группа",
            "Субконто Кт_2": "",
            "Сумма": _SUM,
            "Сумма_руб": _SUM,
        },
    ])

    # ОСВ под этот же набор: 90.01 — кредитовый оборот с НДС (3 × 122 000),
    # 90.03 — дебетовый оборот НДС (3 × 22 000). Разность даёт выручку
    # без НДС: (366 000 − 66 000) / 1000 = 300 тыс.ед. — сходимость точная.
    osv_df = pd.DataFrame({
        "Счет": ["90.01", "90.03"],
        "Кредит_оборот": [3 * _SUM, 0.0],
        "Дебет_оборот": [0.0, 3 * 22_000.0],
    })

    df9001 = _STEP._process_revenue_9001(transactions_all_df, osv_df, context)
    total = float(df9001["выручка_без_ндс_тыс_ед"].sum())
    check(
        abs(total - 300.0) < 1e-6,
        f"выручка без НДС = 300 тыс.ед. — строки без ставки не выпали, НДС не задвоен",
    )
    check(len(df9001) == 3, "все 3 документа сохранились (группировка не потеряла строки)")

    # Сверка с ОСВ прошла бы с разницей 0 — если бы она не развалилась, шаг упал
    # бы с ConvergenceError, и до следующих проверок мы бы не дошли.
    check(True, "сверка с ОСВ прошла (ConvergenceError не брошен)")

    e2e_files = list(get_output_dir("warnings").glob("nds_missing_rows_smoke_90_01_test.xlsx"))
    check(len(e2e_files) == 1, "Excel-аудит сохранён в warnings/ под именем компании")
    if e2e_files:
        audit_e2e = pd.read_excel(e2e_files[0])
        check(len(audit_e2e) == 2, "в аудите ровно 2 корректировки")
        check(
            (audit_e2e["источник"] == "аналоги").all()
            and audit_e2e["восстановленная_ставка"].astype(float).sub(0.22).abs().max() < 1e-9,
            "обе строки восстановлены по аналогам со ставкой 22%",
        )
except Exception as e:  # noqa: BLE001 — смоук должен показать реальную ошибку
    import traceback
    traceback.print_exc()
    check(False, f"сквозной прогон 90.01: исключение {e!r}")

# ==========================================================================
# Уборка: папка запуска остаётся от configure_run(), иначе каждый запуск
# смоука оставлял бы в _OUTPUT_DATA свой run_<timestamp>.
shutil.rmtree(run_dir, ignore_errors=True)

print("\n=== ИТОГ ===")
if failures:
    print(f"SMOKE_FAIL ({len(failures)}):")
    for f in failures:
        print("  -", f)
    sys.exit(1)
print("SMOKE_OK")