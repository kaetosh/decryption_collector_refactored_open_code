def create_corrections_template(path: Path) -> bool:
    """Создаёт шаблон файла правил: пустой лист «Правки» + лист «Справка».

    Лист «Правки» остаётся БЕЗ строк-примеров намеренно: пример, оставленный
    в нём, на следующем прогоне выполнился бы как настоящее правило и молча
    исправил не то. Все примеры живут в «Справке».

    При создании шаблона падает предупреждение про архивацию старого файла (B):
    см. load_corrections, там же вызывается для уже существующего файла.
    """
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        with pd.ExcelWriter(path, engine="openpyxl") as writer:
            pd.DataFrame(columns=list(TEMPLATE_COLUMNS)).to_excel(
                writer,
                sheet_name=MC.TEMPLATE_SHEET_RULES,
                index=False,
            )
            pd.DataFrame(_help_rows(), columns=["что", "пояснение"]).to_excel(
                writer,
                sheet_name=MC.TEMPLATE_SHEET_HELP,
                index=False,
            )
            help_sheet = writer.sheets[MC.TEMPLATE_SHEET_HELP]
            DataSaver._apply_excel_formatting(help_sheet)
            help_sheet.column_dimensions["A"].width = 42
            help_sheet.column_dimensions["B"].width = 96
    except Exception as exc:  # noqa: BLE001 — шаблон не влияет на расчёт
        logger.warning(
            "[!] Не удалось создать шаблон файла ручных корректировок '{}': {}",
            to_relative(path),
            exc,
        )
        return False
    return True


def _warn_stale_file(path: Path, rules_count: int) -> None:
    """(B) Напоминает, что делать со старым файлом правок при новом прогоне.

    Прогону нужен один файл, но прогоны у нас — по компаниям и периодам.
    Старый файл, оставленный от прошлого прогона, продолжит применяться и к
    новому. Мы не останавливаем прогон (это штатная ситуация, а не ошибка),
    но напоминаем бухгалтеру: если компания/период сменился — сделайте копию
    и начните с чистого листа.

    Предупреждение уместно только когда в файле есть применимые правила:
    пустой автосозданный шаблон и файл без применимых правил до вызова уже
    вышли из load_corrections (см. return выше), поэтому здесь rules_count >= 1.
    Два сообщения, а не одно: консольный формат логгера режет строки, а сводка
    предупреждений (титульный лист) — до 200 символов. Первое — факт,
    второе — что делать.

    Args:
        path: путь к файлу правил.
        rules_count: сколько применимых правил загружено из файла.
    """
    logger.warning(
        "[!] Ручные корректировки: используем существующий файл '{}' — "
        "применятся {} правил.",
        to_relative(path),
        rules_count,
    )
    logger.warning(
        "[!] Ручные корректировки: если файл остался от прошлого прогона "
        "(другая компания или период), перенесите его в архив — иначе старые "
        "правила применятся и к этому прогону. Пример: mv '{name}' '{name}_архив_{run}'.",
        name=path.name,
        run=get_run_id(),
    )



def resolve_corrections_file(directory: Optional[Path] = None) -> Path:
    """Путь к файлу правил: _INPUT_DATA/_corrections/Правки.xlsx.

    Args:
        directory: Папка с файлом (по умолчанию CORRECTIONS_DIR). Параметр
            нужен смоукам: тесты не должны трогать реальный файл пользователя.

    Returns:
        Путь к файлу (может не существовать — это проверяет вызывающий).
    """
    base = Path(directory) if directory is not None else CORRECTIONS_DIR
    return base / CORRECTIONS_FILE_NAME


def _sheet_names(path: Path) -> list[str]:
    """Имена листов файла (для подсказки в ошибке). Пустой список — не страшно."""
    try:
        with pd.ExcelFile(path) as book:
            return list(book.sheet_names)
    except Exception:  # noqa: BLE001 — подсказка, её отсутствие не должно ломать разбор
        return []


def _read_rules_sheet(path: Path) -> pd.DataFrame:
    """Читает лист правил и приводит его к строковым типам.

    Все значения читаются как строки: правило «новое значение = 3 лица» не должно
    превращаться в число из-за того, что Excel хранит ячейку числом. Имена
    колонок обрезаются — бухгалтер часто оставляет «признак ».

    Raises:
        InputDataError: файл не читается или листа нет.
    """
    try:
        df = pd.read_excel(
            path,
            sheet_name=CORRECTIONS_SHEET_NAME,
            dtype="string",
        )
    except PermissionError as exc:
        raise InputDataError(
            f"Файл ручных корректировок '{path.name}' не удалось прочитать: "
            f"нет прав на чтение. Закройте файл в Excel и повторите запуск"
        ) from exc
    except ValueError as exc:
        # openpyxl отвечает ValueError на неточное имя листа — самый частый
        # случай, когда бухгалтер переименовал лист «Правки»
        available = _sheet_names(path)
        hint = f" Доступные листы: {available}" if available else ""
        raise InputDataError(
            f"Файл ручных корректировок '{path.name}': не удалось прочитать "
            f"лист '{CORRECTIONS_SHEET_NAME}'.{hint}"
        ) from exc
    except Exception as exc:
        raise InputDataError(
            f"Файл ручных корректировок '{path.name}' не удалось прочитать: {exc}"
        ) from exc

    df.columns = [str(col).strip() for col in df.columns]
    return df



def _validate_structure(df: pd.DataFrame, path: Path) -> None:
    """Проверяет, что в файле есть колонки, без которых правила не читаются.

    Raises:
        InputDataError: нет обязательных колонок; в тексте — что в файле есть.
    """
    missing = [col for col in REQUIRED_COLUMNS if col not in df.columns]
    if not missing:
        return

    raise InputDataError(
        f"Файл ручных корректировок '{path.name}' (лист '{CORRECTIONS_SHEET_NAME}'): "
        f"нет обязательных столбцов {missing}. В файле есть: {list(df.columns)}. "
        f"Нужен шаблон: «{MC.COL_FEATURE}» — какой признак меняем, "
        f"«{MC.COL_NEW_VALUE}» — новое значение; селекторы (например «счет», "
        f"«субконто») — любые дополнительные столбцы."
    )


def _normalize_values(df: pd.DataFrame) -> pd.DataFrame:
    """Приводит значения файла к тому же виду, что и значения в данных.

    Данные проходят Step.clean_whitespace (pipeline/base.py): пробелы по краям
    срезаются, внутренние схлопываются в один. Значения правил нормализуются
    так же — иначе двойной пробел внутри имени контрагента, вписанный в файл,
    тихо не совпал бы с данными, а правило ушло бы в «Не применились».
    """
    for col in df.columns:
        df[col] = (
            df[col]
            .astype("string")
            .str.strip()
            .str.replace(r"\s+", " ", regex=True)
            .str.strip()
            .replace({"": pd.NA})
        )
    return df


def _drop_incomplete_rules(df: pd.DataFrame, path: Path) -> pd.DataFrame:
    """Убирает строки без признака или без нового значения.

    Такие строки не пропускаются молча: бухгалтер, увидев «зелёный» отчёт,
    решит, что договор поправлен. Поэтому каждая — WARNING со строкой файла.
    """
    incomplete = df[MC.COL_FEATURE].isna() | df[MC.COL_NEW_VALUE].isna()
    if not incomplete.any():
        return df

    for index, record in df.loc[incomplete].iterrows():
        missing = [
            col
            for col in (MC.COL_FEATURE, MC.COL_NEW_VALUE)
            if pd.isna(record.get(col))
        ]
        logger.warning(
            "[!] Правки: строка {} файла '{}' пропущена — не заполнено {}. "
            "Дополните правило или удалите строку.",
            index + 2,  # +1 — строка заголовка, +1 — индекс с нуля
            to_relative(path),
            ", ".join(f"«{col}»" for col in missing),
        )
    return df.loc[~incomplete].reset_index(drop=True)


def _validate_area(df: pd.DataFrame, path: Path) -> pd.DataFrame:
    """Нормализует «область» и отсекает незнакомые значения.

    Пустая область = 'баланс' (по умолчанию), чтобы самый частый случай
    («поправить признак в балансе») не требовал лишней колонки.
    """
    if MC.COL_AREA not in df.columns:
        df[MC.COL_AREA] = MC.DEFAULT_AREA
        return df

    area = df[MC.COL_AREA].astype("string").str.strip().str.casefold().fillna(MC.DEFAULT_AREA)
    known = {MC.AREA_BALANCE, MC.AREA_OPU}
    unknown = ~area.isin(known)
    if unknown.any():
        for index, value in zip(df.index[unknown], area[unknown]):
            logger.warning(
                "[!] Правки: строка {} файла '{}' пропущена — неизвестная область "
                "«{}» (допустимо: {}).",
                index + 2,
                to_relative(path),
                value,
                ", ".join(sorted(known)),
            )
    # Нормализованное значение кладём обратно: с ним работает отбор правил в
    # шаге, оно же попадает в лист «Применённые правки», и там должно быть
    # «баланс», а не «Баланс» из файла
    df[MC.COL_AREA] = area
    return df.loc[~unknown].reset_index(drop=True)


def load_corrections(
    directory: Optional[Path] = None,
    create_template: bool = True,
) -> pd.DataFrame:
    """Загружает правила ручных корректировок.

    Args:
        directory: Папка с файлом (по умолчанию CORRECTIONS_DIR). Нужен смоукам.
        create_template: Если файла нет — создать шаблон со справкой (D).
            Параметр нужен смоукам: тестам не нужен побочный файл на диске.

    Returns:
        DataFrame с правилами. Пустой, если файла нет или пригодных правил нет.

    Raises:
        InputDataError: файл есть, но его нельзя использовать (нечитаем,
            нет листа «Правки», нет обязательных колонок).
    """
    path = resolve_corrections_file(directory)
    if not path.exists():
        if create_template and create_corrections_template(path):
            logger.info(
                "Ручные корректировки: файла не было — создан шаблон '{}'. "
                "Заполните лист «{}» (описание в листе «{}») и запустите прогон "
                "заново; пока файл пуст, отчёт собирается как обычно.",
                to_relative(path),
                MC.TEMPLATE_SHEET_RULES,
                MC.TEMPLATE_SHEET_HELP,
            )
        else:
            logger.info(
                "Ручные корректировки: файла '{}' нет — работаем без правок. "
                "Создайте его, если нужно поправить признак выгрузки: одна строка — "
                "одно правило, обязательны «{}» и «{}», селектор «счёт» — минимум.",
                to_relative(path),
                MC.COL_FEATURE,
                MC.COL_NEW_VALUE,
            )
        return pd.DataFrame()

    df = _read_rules_sheet(path)
    _validate_structure(df, path)

    # Полностью пустые строки (остаток форматирования в файле) не должны
    # превращаться в «неприменимые правила»
    df = df.dropna(how="all")
    if df.empty:
        logger.info("Ручные корректировки: файл '{}' пуст", to_relative(path))
        return pd.DataFrame()

    df = _normalize_values(df)
    df = _drop_incomplete_rules(df, path)
    df = _validate_area(df, path)

    if df.empty:
        logger.warning(
            "Ручные корректировки: в файле '{}' не осталось ни одного применимого правила",
            to_relative(path),
        )
        return pd.DataFrame()

    # (B) Файл существует И в нём есть применимые правила — напоминаем про
    # возможный артефакт прошлого прогона. Пустой автосозданный шаблон и файл
    # без применимых правил вышли через return выше и не пугают пользователя.
    _warn_stale_file(path, len(df))

    # А. ПРЕДУПРЕЖДЕНИЕ О «УНИВЕРСАЛЬНЫХ» ПРАВИЛАХ БЕЗ ПРИВЯЗКИ К КОМПАНИИ/ПЕРИОДУ
    # Пустая ячейка — штатно значит «любая». Но если бухгалтер оставил правило
    # из прошлого прогона без привязки к компании, оно применится к новому прогону
    # незаметно. Здесь мы говорим о нём прямо и подсказываем что делать.
    _warn_universal_rules(df, path)

    logger.info(
        "Ручные корректировки: загружено {} правил из '{}'",
        len(df),
        to_relative(path),
    )
    return df

def _warn_universal_rules(df: pd.DataFrame, path: Path) -> None:
    """Предупреждает о правилах без привязки к компании/периоду (A).

    Пустая ячейка в `компания`/`период` штатно значит «любая» — один файл правил
    обслуживает все прогоны. Опасность ровно та, из-за которой задан вопрос: если
    бухгалтер оставил правило из прошлого прогона и не привязал его к компании,
    оно применится к совершенно новому прогону незаметно. Поэтому здесь мы
    перечисляем такие правила и подсказываем, как от них избавиться.

    Показываем первые UNIVERSAL_PREVIEW штук; остальные — одной строкой «и ещё N».
    Вызывается только при загрузке файла, один раз на прогон (файл читается один
    раз — см. get_corrections).
    """
    # Пустое значение в колонке: ячейка не заполнена либо содержит только пробелы
    def _is_blank(column: str) -> pd.Series:
        if column not in df.columns:
            return pd.Series(True, index=df.index)
        return df[column].isna() | df[column].astype("string").str.strip().eq("")

    blank_company = _is_blank(MC.COL_COMPANY)
    blank_period = _is_blank(MC.COL_PERIOD)
    # Риск «устаревшего правила»: пусты ОБЕ колонки. Тогда правку, заведённую
    # для одного прогона, подхватит другой прогон — другая компания и/или
    # другой период, где она, скорее всего, не нужна. Правило с заполненной
    # компанией, но пустым периодом такому риску не подлежит: компания-то
    # совпадает, вопрос только в периоде.
    unmapped = blank_company & blank_period
    if not unmapped.any():
        return

    # Логировать многострочный список нельзя: консольный формат логгера режет
    # до 500 символов, а это уходит и в сводку предупреждений на титульном листе.
    # Поэтому — короткая шапка + построчное перечисление в виде отдельных WARNING.
    # np.flatnonzero, а не .nonzero(): серия nullable boolean (pd.BooleanArray)
    # .nonzero() не имеет.
    rows = np.flatnonzero(unmapped.fillna(False).to_numpy())
    preview = rows[:UNIVERSAL_PREVIEW]
    for position in preview:
        rule = df.iloc[position]
        # Показываем только селекторы (без служебных колонок файла)
        selectors = "; ".join(
            f"{col}={value}"
            for col, value in rule.items()
            if col in TEMPLATE_COLUMNS
            and col not in (MC.COL_FEATURE, MC.COL_NEW_VALUE, MC.COL_OLD_VALUE, MC.COL_COMMENT)
            and pd.notna(value)
        ) or "—"
        logger.warning(
            "[!] Ручные корректировки: строка {} файла '{}' — правило без привязки "
            "к компании и периоду (пусты обе ячейки). Оно сработает в ЛЮБОМ прогоне: "
            "[{}] → {} = {}. Если правка была нужна только для одной компании/периода — "
            "заполните колонки «{}»/«{}», либо удалите строку.",
            position + 2,  # +1 — заголовок, +1 — индекс с нуля
            to_relative(path),
            selectors,
            rule.get(MC.COL_FEATURE),
            rule.get(MC.COL_NEW_VALUE),
            MC.COL_COMPANY,
            MC.COL_PERIOD,
        )
    rest = len(rows) - len(preview)
    if rest > 0:
        logger.warning(
            "[!] Ручные корректировки: и ещё {} таких правил в файле '{}' — "
            "полный список на листе «{}», колонка «{}» пуста.",
            rest,
            to_relative(path),
            MC.TEMPLATE_SHEET_RULES,
            MC.COL_COMPANY,
        )


def get_corrections(context) -> pd.DataFrame:
    """Правила из контекста: читаются с диска один раз за прогон.

    Шагов два (12а — баланс, 18а — ОПУ), а файл один: без кэша он читался бы
    дважды, и при правке файла между шагами они увидели бы разное.

    Args:
        context: ProcessingContext текущего запуска.

    Returns:
        DataFrame с правилами (возможно пустой).
    """
    cached = context.data.get(MC.CONTEXT_KEY)
    if cached is None:
        cached = load_corrections()
        context.data[MC.CONTEXT_KEY] = cached
    return cached
