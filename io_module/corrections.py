# -*- coding: utf-8 -*-
"""Загрузка файла ручных корректировок признаков (_INPUT_DATA/_corrections/Правки.xlsx).

Зачем этот файл нужен
---------------------
Выгрузки из 1С неидеальны. Классический случай: на договоре по счёту 60
признак «инвест_договор» стоит «нет», а по факту «да». Ошибочный признак уезжает
в сырые выгрузки, а оттуда — в ключ меппинга (BalanceReportConstants.MAPPING_KEYS),
и строка получает не тот счёт_фо. При этом справочник `Меппинг_бб` исправен:
комбинация с признаком «нет» в нём есть, поэтому шаг 13 отрабатывает штатно,
конвейер собирает «зелёный» отчёт, а ошибка остаётся невидимой.

Сам отчёт здесь ни при чём: он уже собран из неверных данных. Исправлять нужно
до меппинга, то есть в данных.

Как это сделано
---------------
Бухгалтер кладёт сюда `Правки.xlsx` (лист `Правки`) — одна строка = одно правило:

    | счет  | субконто        | признак        | новое_значение | старое_значение |
    | 60.01 | Договор №141/24 | инвест_договор | да             | нет            |

Любая колонка, кроме служебных, работает как селектор: пустая ячейка — «не важно».
Минимум — `счет`, иначе правило «съест» весь кадр. Правила применяются
ДО шага 13 (баланс) и ДО шага 19 (ОПУ) — см. pipeline/steps/_corrections_base.py.

Файл — память правок, а не разовая заплатка: он лежит в `_INPUT_DATA/_corrections/`
и переживает прогон, поэтому одна и та же ошибка в 1С не разбирается заново
каждый период.

Границы ответственности
-----------------------
Модуль только ЧИТАЕТ и проверяет структуру файла. Применение правил и вся
диагностика — в pipeline/steps/_corrections_base.py; сюда шаги не ходят.

Поведение
---------
- Файла нет           → пустой кадр + INFO «работаем без правок». Штатный случай.
- Файл нечитаем       → InputDataError (штатный [STOP], см. cli/main.py).
- Нет листа/колонок   → InputDataError со списком того, что в файле есть:
                        бухгалтеру полезнее увидеть реальные имена колонок,
                        чем гадать по названиям.
- Правило неполное    → WARNING + пропуск. Неполное правило молча ничего
                        не делает — худший исход, поэтому оно обязано быть
                        заметным, но не останавливать прогон.
"""

