class ManualCorrectionsConstants:
    """Ручные корректировки признаков (файл Правки.xlsx, шаги 12а и 18а).

    Назначение: выгрузки из 1С неидеальны — например, на договоре по счёту 60
    признак «инвест_договор» стоит «нет», а по факту «да». Ошибочный признак
    уезжает в сырые выгрузки, а оттуда — в ключ меппинга, и строка получает не
    тот счёт_фо. Справочник при этом исправен, поэтому конвейер отрабатывает
    штатно, а ошибка остаётся невидимой.

    Решение — память правок: бухгалтер описывает правило в файле, пайплайн
    применяет его ДО шага 13 (баланс) и ДО шага 19 (ОПУ), после чего счёт_фо
    тянется из Меппинг_бб/Меппинг_опу обычным порядком. Справочник остаётся
    единственной точкой правды для «куда попасть», файл правок — память о том,
    что 1С врёт.

    Одна строка файла = одно правило. Любая колонка, кроме служебных
    (RESERVED_COLUMNS), работает как селектор: пустая ячейка — «не важно».
    """
    # ─── Служебные колонки файла правил ───
    COL_COMPANY = "компания"           # пусто = любая компания
    COL_PERIOD = "период"              # пусто = любой период
    COL_AREA = "область"               # 'баланс' (по умолчанию) | 'опу'
    COL_FEATURE = "признак"            # какой признак меняем
    COL_NEW_VALUE = "новое_значение"   # новое значение (обязательно)
    COL_OLD_VALUE = "старое_значение"  # если задано — проверка, что правило ещё актуально
    COL_COMMENT = "комментарий"        # свободный текст, уходит в лог и в отчёт

    # Колонки, которые не являются селекторами
    RESERVED_COLUMNS = (
        COL_COMPANY,
        COL_PERIOD,
        COL_AREA,
        COL_FEATURE,
        COL_NEW_VALUE,
        COL_OLD_VALUE,
        COL_COMMENT,
    )

    # ─── Значения колонки «область» ───
    AREA_BALANCE = "баланс"
    AREA_OPU = "опу"
    DEFAULT_AREA = AREA_BALANCE

    # ─── Контекст ───
    CONTEXT_KEY = "manual_corrections"           # кэш загруженных правил
    SUMMARY_KEY = "manual_corrections_summary"   # сводка для титульного листа
    MARKER_COL = "ручная_правка"                 # колонка-маркер в кадре ОСВ/журнала

    # ─── Аудит в mismatches/ ───
    AUDIT_PREFIX = "manual_corrections_"
    AUDIT_SHEET_APPLIED = "Применённые правки"
    AUDIT_SHEET_SKIPPED = "Не применились"
    AUDIT_SHEET_DETAIL = "Затронутые строки"

    # Сколько затронутых правилом строк показывать в листе «Затронутые строки».
    # Ограничение страхует от файла на сотни мегабайт, если правило по ошибке
    # задело весь кадр; о срезе пишется WARNING в лог (и он попадает в сводку
